// Generates src/data/emoji.generated.ts — only the Twemoji SVGs the game actually uses,
// inlined as data URIs. Why: system emoji differ per device, and Android 10/11 phones (very
// common in Nepal) can't draw newer emoji like 🪷 🪞 🦬 at all. Bundling SVGs makes every
// picture identical everywhere and works offline.
// Twemoji graphics: © Twitter/X and contributors, CC-BY 4.0 (attribution in Credits screen).

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = resolve(root, 'node_modules/@twemoji/svg');

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return walk(p);
    return /\.(ts|tsx)$/.test(f) && !f.endsWith('.generated.ts') ? [p] : [];
  });
}

// pictographs (with ZWJ sequences), plus flags: a pair of regional-indicator letters (🇳🇵 🇬🇧)
const RE = /\p{Extended_Pictographic}️?(?:‍\p{Extended_Pictographic}️?)*|\p{Regional_Indicator}{2}/gu;
const found = new Set();
for (const file of walk(resolve(root, 'src'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(RE)) found.add(m[0]);
}

const out = {};
const missing = [];
for (const e of [...found].sort()) {
  const cps = [...e].map((c) => c.codePointAt(0).toString(16));
  const noFe0f = e.includes('‍') ? cps : cps.filter((c) => c !== 'fe0f');
  const candidates = [noFe0f.join('-'), cps.join('-')];
  const name = candidates.find((n) => existsSync(join(svgDir, `${n}.svg`)));
  if (!name) { missing.push(e); continue; }
  const svg = readFileSync(join(svgDir, `${name}.svg`), 'utf8').trim();
  out[e] = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

writeFileSync(
  resolve(root, 'src/data/emoji.generated.ts'),
  `// AUTO-GENERATED by scripts/gen-emoji.mjs from @twemoji/svg (CC-BY 4.0). Do not edit.\n` +
    `export const EMOJI: Record<string, string> = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`,
);
console.log(`emoji: ${Object.keys(out).length} bundled`, missing.length ? `MISSING: ${missing.join(' ')}` : '');
if (missing.length) process.exitCode = 1;
