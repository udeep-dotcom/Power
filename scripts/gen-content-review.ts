// Writes docs/CONTENT_REVIEW.md — a checklist of EVERY learner-facing fact and word, generated
// from the data files so the reviewer always sees exactly what ships.
// Run: node scripts/gen-content-review.ts
import { writeFileSync } from 'node:fs';
import { LETTERS } from '../src/data/alphabet.ts';
import { STICKERS } from '../src/data/journey.ts';
import { MATRAS } from '../src/data/barakhari.ts';
import { DECKS, PROVINCES, QUIZ } from '../src/data/nepal.ts';

const L: string[] = [];
L.push('# Content review checklist', '');
L.push('> Generated by `node scripts/gen-content-review.ts` — do not edit by hand; edit `src/data/*` and regenerate.', '');
L.push('**Reviewer:** a Nepali primary-school teacher (and, for facts, a second person checking sources).');
L.push('Tick each row when the Nepali spelling, the example word, the picture and the English gloss are all correct and child-appropriate.', '');
L.push('Items marked ⚠ are known compromises that need a decision.', '');

L.push('## 1. Letters and example words (49)', '');
L.push('| ✓ | Letter | Roman | Example word | Highlight | Meaning | Picture | Notes |', '|---|---|---|---|---|---|---|---|');
const notes: Record<string, string> = {
  ah: '⚠ No common word starts with अः; using प्रातः (ends with ः). Many charts show अः without a word.',
  nga: 'Letter appears at the END of the word (never starts a word).',
  nya: 'Letter appears in the MIDDLE (as ञ्). ⚠ Confirm पञ्जा vs पन्जा spelling preference.',
  nna: 'Letter appears at the END of the word.',
  ii: '⚠ ईगल is a loanword; ईख (sugarcane) is more traditional but hard to picture.',
  ya: '⚠ Picture is a bison emoji standing in for a yak until custom art exists.',
  wa: 'Nepali usually pronounces व as "ba" — romanised as wa/ba.',
  pha: 'फूल shown as hibiscus emoji (placeholder).',
  e: 'Picture is the Nepali numeral १.',
  ssa: 'Picture is a hand-drawn hexagon.',
  jha: 'Picture is the Nepal flag. Font shows the Nepali form of झ (Noto Sans Devanagari, lang="ne").',
};
for (const l of LETTERS) {
  L.push(`| ☐ | **${l.char}** | ${l.roman} | ${l.word} | ${l.hl} | ${l.meaning} | ${l.pic} | ${notes[l.id] ?? ''} |`);
}

L.push('', '## 2. Provinces (7)', '');
L.push('| ✓ | Province | Capital | Fact (ne) | Fact (en) |', '|---|---|---|---|---|');
for (const p of PROVINCES) L.push(`| ☐ | ${p.name.ne} / ${p.name.en} | ${p.capital.ne} / ${p.capital.en} | ${p.fact.ne} | ${p.fact.en} |`);
L.push('', '⚠ Province capitals changed recently (Lumbini → Deukhuri, Sudurpashchim → Godawari). Re-confirm against the latest official notice before each release.', '');

L.push('## 3. Fact cards', '');
for (const d of DECKS) {
  L.push(`### ${d.title.ne} / ${d.title.en}`, '', '| ✓ | Card | Fact (ne) | Fact (en) |', '|---|---|---|---|');
  for (const c of d.cards) L.push(`| ☐ | ${c.title.ne} / ${c.title.en} | ${c.fact.ne} | ${c.fact.en} |`);
  L.push('');
}

L.push('## 4. Stickers (rewards)', '', '| ✓ | Sticker | Fact (ne) | Fact (en) |', '|---|---|---|---|');
for (const s of STICKERS) L.push(`| ☐ | ${s.pic} ${s.name.ne} / ${s.name.en} | ${s.fact.ne} | ${s.fact.en} |`);

L.push('', '## 5. बाह्रखरी vowel signs (12)', '', '| ✓ | Sign | Name (ne) | Example with क |', '|---|---|---|---|');
for (const m of MATRAS) L.push(`| ☐ | ${m.sign ? '◌' + m.sign : '—'} | ${m.name.ne} | क${m.sign} |`);
L.push('', '⚠ Traditional बाह्रखरी has 12 forms and leaves out ृ (ऋकार); confirm this matches the school curriculum.', '');

L.push('', '## 6. Quiz (correct answer listed first)', '', '| ✓ | Question | Correct | Distractors |', '|---|---|---|---|');
for (const q of QUIZ) {
  const ok = q.options[q.answer];
  const rest = q.options.filter((_, i) => i !== q.answer).map((o) => o.label.ne).join(', ');
  L.push(`| ☐ | ${q.q.ne} | ${ok.label.ne} | ${rest} |`);
}
L.push('');
writeFileSync(new URL('../docs/CONTENT_REVIEW.md', import.meta.url), L.join('\n'));
console.log('docs/CONTENT_REVIEW.md written');
